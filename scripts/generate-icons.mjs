// Turns the SVG files in assets/icons into React components (frontend/src/icons/icons.tsx).
// The SVGs are drawn in white; the components use currentColor so they follow the
// surrounding text colour (idle, hover, active) like any other icon in the app.
//
//   npm run icons
//
// Edit or add files in assets/icons, run the command, commit the result.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "assets", "icons");
const target = join(root, "frontend", "src", "icons", "icons.tsx");

const pascal = (file) =>
  file
    .replace(/\.svg$/i, "")
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const camel = (attr) => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function parsePaths(svg, file) {
  const paths = [];
  for (const [, attrs] of svg.matchAll(/<path\b([^>]*?)\/?>/g)) {
    const found = Object.fromEntries([...attrs.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));
    if (!found.d) throw new Error(`${file}: a <path> has no d attribute`);
    paths.push(found);
  }
  if (paths.length === 0) throw new Error(`${file}: no <path> elements found (only paths are supported)`);
  if (/<(circle|rect|ellipse|line|polyline|polygon|g)\b/.test(svg)) throw new Error(`${file}: only <path> elements are supported; convert other shapes to paths`);
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${file}: expected viewBox="0 0 24 24"`);
  return paths;
}

export function generate(dir = source) {
  const files = readdirSync(dir).filter((f) => f.toLowerCase().endsWith(".svg")).sort();
  const parts = files.map((file) => {
    const paths = parsePaths(readFileSync(join(dir, file), "utf8"), file);
    const body = paths
      .map((p) => {
        // Colours and the stroke width come from the component; geometry and line styling from the file.
        const extra = ["stroke-linecap", "stroke-linejoin", "fill-rule", "clip-rule"].filter((k) => p[k]).map((k) => ` ${camel(k)}="${p[k]}"`).join("");
        return `      <path d="${p.d}"${extra} />`;
      })
      .join("\n");
    return `export function Icon${pascal(file)}({ size = 24, strokeWidth = 1.5, className }: IconProps) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={strokeWidth} className={className} aria-hidden="true">
${body}
    </svg>
  );
}`;
  });
  return `// Generated by scripts/generate-icons.mjs from the SVG files in assets/icons. Do not edit by hand:
// change the SVGs and run \`npm run icons\`.

export interface IconProps {
  size?: number;
  strokeWidth?: number;
  className?: string;
}

${parts.join("\n\n")}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = generate();
  writeFileSync(target, out);
  console.log(`Wrote ${target} (${out.split("\n").filter((l) => l.startsWith("export function")).length} icons)`);
}
